<?php

declare(strict_types=1);

namespace App\DTO\Siswa;

use App\Entity\Siswa;

final readonly class SiswaResponseDTO
{
    public function __construct(
        public int $id,
        public string $nis,
        public ?string $nisn,
        public ?string $nik,
        public string $namaLengkap,
        public ?string $namaPanggilan,
        public ?string $namaArab,
        public string $jenisKelamin,
        public string $jenisKelaminLabel,
        public string $jenisKelaminBadge,
        public ?string $tempatLahir,
        public ?string $tanggalLahir,
        public ?string $agama,
        public ?string $alamat,
        public ?string $rt,
        public ?string $rw,
        public ?string $kelurahan,
        public ?string $kecamatan,
        public ?string $kabupatenKota,
        public ?string $provinsi,
        public ?string $kodePos,
        public ?string $nomorHp,
        public ?string $email,
        public ?int $kelasId,
        public ?string $kelasNama,
        public ?int $kelasTingkat,
        public ?string $kelasJurusan,
        public string $status,
        public string $statusLabel,
        public string $statusBadge,
        public ?string $namaAyah,
        public ?string $pekerjaanAyah,
        public ?string $penghasilanAyah,
        public ?string $noHpAyah,
        public ?string $namaIbu,
        public ?string $pekerjaanIbu,
        public ?string $penghasilanIbu,
        public ?string $noHpIbu,
        public ?string $namaWali,
        public ?string $hubunganWali,
        public ?string $pekerjaanWali,
        public ?string $noHpWali,
        public ?string $alamatOrangTua,
        public ?int $anakKe,
        public ?int $jumlahSaudara,
        public ?string $tanggalMasuk,
        public ?string $asalSekolah,
        public ?string $fotoUrl,
        public ?string $catatan,
        public bool $isActive,
        public ?int $userId,
        public ?string $userUsername,
        public string $createdAt,
    ) {}

    public static function fromEntity(Siswa $siswa): self
    {
        $kelas = $siswa->getKelas();
        $user = $siswa->getUser();

        return new self(
            id: (int) $siswa->getId(),
            nis: $siswa->getNis(),
            nisn: $siswa->getNisn(),
            nik: $siswa->getNik(),
            namaLengkap: $siswa->getNamaLengkap(),
            namaPanggilan: $siswa->getNamaPanggilan(),
            namaArab: $siswa->getNamaArab(),
            jenisKelamin: $siswa->getJenisKelamin()->value,
            jenisKelaminLabel: $siswa->getJenisKelamin()->label(),
            jenisKelaminBadge: $siswa->getJenisKelamin()->badgeClass(),
            tempatLahir: $siswa->getTempatLahir(),
            tanggalLahir: $siswa->getTanggalLahir()?->format('Y-m-d'),
            agama: $siswa->getAgama(),
            alamat: $siswa->getAlamat(),
            rt: $siswa->getRt(),
            rw: $siswa->getRw(),
            kelurahan: $siswa->getKelurahan(),
            kecamatan: $siswa->getKecamatan(),
            kabupatenKota: $siswa->getKabupatenKota(),
            provinsi: $siswa->getProvinsi(),
            kodePos: $siswa->getKodePos(),
            nomorHp: $siswa->getNomorHp(),
            email: $siswa->getEmail(),
            kelasId: $kelas !== null ? (int) $kelas->getId() : null,
            kelasNama: $kelas?->getNamaKelas(),
            kelasTingkat: $kelas?->getTingkat(),
            kelasJurusan: $kelas?->getJurusan(),
            status: $siswa->getStatus()->value,
            statusLabel: $siswa->getStatus()->label(),
            statusBadge: $siswa->getStatus()->badgeClass(),
            namaAyah: $siswa->getNamaAyah(),
            pekerjaanAyah: $siswa->getPekerjaanAyah(),
            penghasilanAyah: $siswa->getPenghasilanAyah(),
            noHpAyah: $siswa->getNoHpAyah(),
            namaIbu: $siswa->getNamaIbu(),
            pekerjaanIbu: $siswa->getPekerjaanIbu(),
            penghasilanIbu: $siswa->getPenghasilanIbu(),
            noHpIbu: $siswa->getNoHpIbu(),
            namaWali: $siswa->getNamaWali(),
            hubunganWali: $siswa->getHubunganWali(),
            pekerjaanWali: $siswa->getPekerjaanWali(),
            noHpWali: $siswa->getNoHpWali(),
            alamatOrangTua: $siswa->getAlamatOrangTua(),
            anakKe: $siswa->getAnakKe(),
            jumlahSaudara: $siswa->getJumlahSaudara(),
            tanggalMasuk: $siswa->getTanggalMasuk()?->format('Y-m-d'),
            asalSekolah: $siswa->getAsalSekolah(),
            fotoUrl: $siswa->getFotoUrl(),
            catatan: $siswa->getCatatan(),
            isActive: $siswa->isActive(),
            userId: $user !== null ? (int) $user->getId() : null,
            userUsername: $user?->getUsername(),
            createdAt: $siswa->getCreatedAt()->format('Y-m-d H:i:s'),
        );
    }

    /**
     * @return array<string, mixed>
     */
    public function toArray(): array
    {
        return [
            'id' => $this->id,
            'nis' => $this->nis,
            'nisn' => $this->nisn,
            'nik' => $this->nik,
            'namaLengkap' => $this->namaLengkap,
            'namaPanggilan' => $this->namaPanggilan,
            'namaArab' => $this->namaArab,
            'jenisKelamin' => $this->jenisKelamin,
            'jenisKelaminLabel' => $this->jenisKelaminLabel,
            'jenisKelaminBadge' => $this->jenisKelaminBadge,
            'tempatLahir' => $this->tempatLahir,
            'tanggalLahir' => $this->tanggalLahir,
            'agama' => $this->agama,
            'alamat' => $this->alamat,
            'rt' => $this->rt,
            'rw' => $this->rw,
            'kelurahan' => $this->kelurahan,
            'kecamatan' => $this->kecamatan,
            'kabupatenKota' => $this->kabupatenKota,
            'provinsi' => $this->provinsi,
            'kodePos' => $this->kodePos,
            'nomorHp' => $this->nomorHp,
            'email' => $this->email,
            'kelasId' => $this->kelasId,
            'kelasNama' => $this->kelasNama,
            'kelasTingkat' => $this->kelasTingkat,
            'kelasJurusan' => $this->kelasJurusan,
            'status' => $this->status,
            'statusLabel' => $this->statusLabel,
            'statusBadge' => $this->statusBadge,
            'namaAyah' => $this->namaAyah,
            'pekerjaanAyah' => $this->pekerjaanAyah,
            'penghasilanAyah' => $this->penghasilanAyah,
            'noHpAyah' => $this->noHpAyah,
            'namaIbu' => $this->namaIbu,
            'pekerjaanIbu' => $this->pekerjaanIbu,
            'penghasilanIbu' => $this->penghasilanIbu,
            'noHpIbu' => $this->noHpIbu,
            'namaWali' => $this->namaWali,
            'hubunganWali' => $this->hubunganWali,
            'pekerjaanWali' => $this->pekerjaanWali,
            'noHpWali' => $this->noHpWali,
            'alamatOrangTua' => $this->alamatOrangTua,
            'anakKe' => $this->anakKe,
            'jumlahSaudara' => $this->jumlahSaudara,
            'tanggalMasuk' => $this->tanggalMasuk,
            'asalSekolah' => $this->asalSekolah,
            'fotoUrl' => $this->fotoUrl,
            'catatan' => $this->catatan,
            'isActive' => $this->isActive,
            'userId' => $this->userId,
            'userUsername' => $this->userUsername,
            'createdAt' => $this->createdAt,
        ];
    }
}
